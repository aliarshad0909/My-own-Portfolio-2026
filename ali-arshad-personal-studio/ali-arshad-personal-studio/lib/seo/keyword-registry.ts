// ─────────────────────────────── Helpers & invariants ───────────────────────

export const getKeyword = (id: string) =>
  KEYWORD_REGISTRY.find((k) => k.id === id);

export const keywordsForUrl = (url: string) =>
  KEYWORD_REGISTRY.filter((k) => k.primaryUrl === url);

export const keywordsInCluster = (cluster: KeywordCluster) =>
  KEYWORD_REGISTRY.filter((k) => k.cluster === cluster);

/** Rows whose evidence does not yet justify their state (should be caught by QA). */
export function evidenceGaps(): KeywordOpportunity[] {
  return KEYWORD_REGISTRY.filter(
    (k) =>
      k.state === "Published" &&
      !k.evidenceRequired.every((req) => k.evidenceHave.includes(req)),
  );
}

/** URLs claimed as primary by more than one row — a canonical conflict. */
export function duplicatePrimaryUrls(): string[] {
  const seen = new Map<string, number>();
  for (const k of KEYWORD_REGISTRY) seen.set(k.primaryUrl, (seen.get(k.primaryUrl) ?? 0) + 1);
  return [...seen.entries()].filter(([, n]) => n > 1).map(([url]) => url);
}

/** Duplicate keyword strings — two rows chasing the exact same query. */
export function duplicateKeywords(): string[] {
  const seen = new Map<string, number>();
  for (const k of KEYWORD_REGISTRY) {
    const key = k.keyword.trim().toLowerCase();
    seen.set(key, (seen.get(key) ?? 0) + 1);
  }
  return [...seen.entries()].filter(([, n]) => n > 1).map(([kw]) => kw);
}
