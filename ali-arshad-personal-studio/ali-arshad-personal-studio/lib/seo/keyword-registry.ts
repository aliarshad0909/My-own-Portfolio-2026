/**
 * Central, typed keyword registry.
 *
 * One row per search opportunity. This is the single source of truth for what
 * each page is *about*, which page owns a query, and whether that page has
 * earned the right to be indexed. Titles and canonicals in the app are written
 * to agree with this file; the SEO tests (tests/seo.test.ts) enforce the
 * invariants:
 *
 *   1. No two rows claim the same `primaryUrl` — one canonical owner per URL,
 *      so pages never compete with each other for the same query.
 *   2. A `Published` row must have every `evidenceRequired` item present in
 *      `evidenceHave` — nothing goes live on an unproven claim.
 *   3. `linksTo` / `linksFrom` reference real, known routes.
 *
 * Nothing here promises a ranking. These are the queries each page targets and
 * the honest state of the evidence behind each one.
 */

import type { PublicationState } from "@/lib/seo/publication";

/**
 * Why the searcher is searching — this decides page shape, not just copy.
 * `local` is intent with a place attached ("web developer in texas"); those
 * rows stay gated until there is a genuine local signal to justify a page.
 */
export type SearchIntent =
  | "navigational"
  | "informational"
  | "commercial"
  | "transactional"
  | "local";

/** Pillar grouping. Each cluster has one hub page and a set of spokes. */
export type KeywordCluster =
  | "brand"
  | "service-hub"
  | "service-specialized"
  | "location"
  | "industry"
  | "resource"
  | "tool"
  | "portfolio";

export type KeywordOpportunity = {
  /** Stable id, kebab-case. */
  id: string;
  /** The target query, lower-case as typed by a searcher. */
  keyword: string;
  intent: SearchIntent;
  cluster: KeywordCluster;
  /** The one page that owns this query (its canonical target), path form. */
  primaryUrl: string;
  /** Secondary phrases the same page may also serve. */
  supporting?: string[];
  state: PublicationState;
  /** Conditions that must hold before this row may be `Published`. */
  evidenceRequired: string[];
  /** Conditions satisfied today. `Published` requires this to cover the above. */
  evidenceHave: string[];
  /** Routes this page should link out to (internal link plan). */
  linksTo: string[];
  /** Routes that should link into this page. */
  linksFrom: string[];
  notes?: string;
};

// Evidence predicates reused across rows, so QA output distinguishes
// locally tested demonstrations, publicly deployed demos, verified professional
// work, actual client outcomes and editorial reviews cleanly.
